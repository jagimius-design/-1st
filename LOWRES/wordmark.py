"""Draws the LOW RES wordmark and writes it to wordmark.js.

Each letter of "low res" is a clean geometric shape (strokes of about 8 units on a 30-unit
x-height) sampled on its own pixel grid, so every letter has a different resolution. The top
right pixel of the "s" has broken off and floats above it in signal orange: the stray pixel.

Change UNITS to re-pixelate a letter (a unit must divide 30), then rerun:
    python3 wordmark.py && python3 export.py
"""
import json
import math
from pathlib import Path

XH = 30   # x-height in units
ASC = 15  # ascender above the x-height, for the "l"
UNITS = {"l": 3, "o": 1, "w": 2, "r": 5, "e": 3, "s": 6}


def rect(x0, x1, y0, y1):
    return lambda x, y: x0 <= x <= x1 and y0 <= y <= y1


def ring(cx, cy, ro, ri=0, keep=lambda x, y: True):
    return lambda x, y: ri <= math.hypot(x - cx, y - cy) <= ro and keep(x, y)


def union(*shapes):
    return lambda x, y: any(s(x, y) for s in shapes)


# (width, shape); y runs down from the x-height line (0) to the baseline (30).
SHAPES = {
    "l": (17, union(rect(0, 8, -ASC, 16), ring(14, 16, 14, 6, lambda x, y: y >= 16 and x <= 17))),
    "o": (30, ring(15, 15, 15, 7)),
    "w": (37, union(rect(0, 7, 0, 19), rect(15, 22, 5, 19), rect(30, 37, 0, 19),
                    ring(11, 19, 11, 4, lambda x, y: y >= 19), ring(26, 19, 11, 4, lambda x, y: y >= 19))),
    "r": (30, union(rect(0, 8, 0, 30), ring(20, 16, 16, 8, lambda x, y: y <= 10 and x >= 8))),
    "e": (30, lambda x, y: (ring(15, 15, 15, 7)(x, y) and not (x > 15 and 15 < y < 24))
          or rect(4, 28, 12, 18.5)(x, y)),
    "s": (30, union(rect(7, 30, 0, 7), ring(7, 7, 7, 0, lambda x, y: x <= 7 and y <= 7), rect(0, 7, 7, 11.5),
                    ring(7, 11.5, 7, 0, lambda x, y: x <= 7 and y >= 11.5), rect(7, 23, 11.5, 18.5),
                    ring(23, 18.5, 7, 0, lambda x, y: x >= 23 and y <= 18.5), rect(23, 30, 18.5, 23),
                    ring(23, 23, 7, 0, lambda x, y: x >= 23 and y >= 23), rect(0, 23, 23, 30))),
}


def sample(ch, unit):
    """A letter on a grid of unit-sized pixels; a pixel is on when half its area is inside."""
    width, shape = SHAPES[ch]
    top = -ASC if ch == "l" else 0
    rows = []
    for j in range((XH - top) // unit):
        row = ""
        for i in range(math.ceil(width / unit)):
            hits = sum(shape(i * unit + (a + .5) * unit / 4, top + j * unit + (b + .5) * unit / 4)
                       for a in range(4) for b in range(4))
            row += "X" if hits >= 8 else "."
        rows.append(row)
    return rows


def main():
    letters = [{"char": ch, "unit": UNITS[ch], "rows": sample(ch, UNITS[ch])} for ch in "lowres"]
    s = letters[-1]
    s["rows"][0] = s["rows"][0][:-1] + "."  # the pixel that got away
    data = {
        "height": XH + ASC,
        "gap": 6,
        "space": 16,
        "letters": letters,
        # One pixel up and right of the gap it left, in s-pixels.
        "stray": {"col": len(s["rows"][0]), "row": -2},
    }
    out = Path(__file__).parent / "wordmark.js"
    out.write_text("// Generated by wordmark.py; edit that, not this.\nwindow.LOWRES.wordmark = "
                   + json.dumps(data, indent=1) + ";\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
